BEGIN;

CREATE TABLE IF NOT EXISTS public.stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    address TEXT,
    city TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT stations_latitude_range
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT stations_longitude_range
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

CREATE TABLE IF NOT EXISTS public.station_fuel_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id BIGINT NOT NULL
        REFERENCES public.stations(id) ON DELETE CASCADE,
    fuel_type TEXT NOT NULL
        CHECK (fuel_type IN ('Pertalite', 'Solar', 'Pertamax')),
    availability TEXT NOT NULL DEFAULT 'unknown'
        CHECK (availability IN ('available', 'limited', 'unavailable', 'unknown')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (station_id, fuel_type)
);

CREATE TABLE IF NOT EXISTS public.fuel_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id BIGINT NOT NULL
        REFERENCES public.stations(id) ON DELETE CASCADE,
    fuel_type TEXT NOT NULL
        CHECK (fuel_type IN ('Pertalite', 'Solar', 'Pertamax')),
    availability TEXT NOT NULL
        CHECK (availability IN ('available', 'limited', 'unavailable', 'unknown')),
    queue_level TEXT NOT NULL DEFAULT 'unknown'
        CHECK (queue_level IN ('short', 'medium', 'long', 'unknown')),
    notes TEXT,
    reporter_name TEXT,
    reported_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_stations_city
    ON public.stations(city);

CREATE INDEX IF NOT EXISTS idx_fuel_reports_station_reported
    ON public.fuel_reports(station_id, reported_at DESC);

CREATE INDEX IF NOT EXISTS idx_fuel_reports_fuel_reported
    ON public.fuel_reports(fuel_type, reported_at DESC);

COMMIT;
